-- #1324: a guild officer acts in their own guild, and granting a role or
-- adding a team names the guild it is for.
--
-- Until now every check asked is_guild_officer(), "a guild officer in any
-- guild", and admin_grant() / admin_create_team() worked out the guild by
-- assuming there was only one. Measured 2026-09-23 with a second guild in a
-- rolled-back transaction: Grant Guild Officer, Grant BoE Manager and Add Team
-- all refused, and a We Go Again guild officer added a player to the other
-- guild's roster.
--
-- What changes:
--
-- * Two helpers answer for the caller's own guilds.
--     my_guild_officer_team_ids()   every team in a guild the caller is a
--                                   guild officer of; the once-per-query
--                                   array form for access rules (#1106)
--     is_guild_officer_of_team(id)  whether that team is one of them; never
--                                   null, for function checks
--   is_guild_officer_of(guild_id) (#1643) already answers for a guild.
--
-- * The 22 access rules that admitted (SELECT is_guild_officer()) now admit
--   the row's team in my_guild_officer_team_ids(), generated by exact text
--   substitution from pg_policies, nothing else in any rule changed. people
--   and characters have no team, so they admit a person on a team in one of
--   the caller's guilds, the shape their officer branch already has.
--   audit_log rows with no team (grants, boss caps, bio saves) now read for
--   site admins only: nothing a guild officer sees reads them (the officer
--   tab filters to a team; the Admin page is site admins only).
--
-- * The 23 functions that checked public.is_guild_officer() check
--   is_guild_officer_of_team(<the team they act on>), again by exact
--   substitution of the one call. resolve_person() lists only the teams in
--   the caller's guilds, and incoming_roster shows pending signups to the
--   signup's own guild.
--
-- * write_audit_log() no longer lets a guild officer write a row with no
--   team. Its two callers that do, set_encounter_cap() and
--   set_guild_officer_bios(), write their own row, as create_guild() does.
--
-- * A boss's raider cap is Blizzard's number, not a guild's choice (Kat,
--   2026-10-27): set_encounter_cap() is a site admin's only, and no guild
--   role edits it.
--
-- * Still "any guild", on purpose, because it is stored once for the whole
--   site: the guild officer bio cards (set_guild_officer_bios(), moving to the
--   guild in #1647). is_guild_officer() itself stays for the current site's
--   menus and the bio photo upload; no access rule or other function calls it,
--   and tests/rls/guild-officer-per-guild.test.js fails if one starts to.
--
-- * admin_grant_guild_officer(), admin_grant_boe_manager(), their revokes
--   and admin_create_team() take the guild (p_guild_id). Left out, it is the
--   only guild while there is one, so today's callers keep working, and an
--   error once there are two. The lists return each grant's guild_id.
--   A site admin is site-wide (is_site_admin() reads no guild): its grant row
--   still needs a guild, so it takes the first one, and its duplicate check and
--   revoke ignore the guild.

-- Helpers

create or replace function public.my_guild_officer_team_ids() returns integer[]
language sql stable security definer set search_path to 'public'
as $$
  select coalesce(array_agg(t.id), '{}')
    from guild_grants g
    join people p on p.id = g.person_id
    join teams t on t.guild_id = g.guild_id
   where p.auth_user_id = auth.uid()
     and g.grant_type = 'guild_officer';
$$;

comment on function public.my_guild_officer_team_ids() is
  'Every team, archived included, in a guild the caller holds a guild_officer grant for (#1324). For access rules: team_id = ANY ((SELECT my_guild_officer_team_ids())::integer[]) runs once per query (#1106).';

-- Access rules are evaluated for signed-out reads too, so anon needs it, as
-- it does my_officer_team_ids(); it answers an empty array without a sign-in.
revoke all on function public.my_guild_officer_team_ids() from public;
grant execute on function public.my_guild_officer_team_ids() to anon, authenticated;

create or replace function public.is_guild_officer_of_team(p_team_id integer) returns boolean
language sql stable security definer set search_path to 'public'
as $$
  select coalesce(p_team_id = any (public.my_guild_officer_team_ids()), false);
$$;

comment on function public.is_guild_officer_of_team(integer) is
  'Whether the team is in a guild the caller holds a guild_officer grant for (#1324). False, never null, for a null or unknown team.';

revoke all on function public.is_guild_officer_of_team(integer) from public;
revoke execute on function public.is_guild_officer_of_team(integer) from anon;
grant execute on function public.is_guild_officer_of_team(integer) to authenticated;

comment on function public.is_guild_officer() is
  'Whether the caller holds a guild_officer grant in any guild. For deciding what to show only: access checks ask is_guild_officer_of_team() or my_guild_officer_team_ids() (#1324).';

