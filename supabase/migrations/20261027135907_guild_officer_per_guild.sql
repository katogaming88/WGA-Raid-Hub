create function public.admin_grant(p_grant_type text, p_discord_id text, p_label text, p_guild_id integer)
returns integer
language plpgsql security definer set search_path to 'public'
as $$
declare
  v_person integer;
  v_guild integer;
  v_id integer;
begin
  if not public.is_site_admin() then
    raise exception 'Not authorized';
  end if;

  v_guild := coalesce(p_guild_id, only_guild_id());

  if exists (
    select 1 from guild_grants g
      join people p on p.id = g.person_id
     where p.discord_id = p_discord_id
       and g.grant_type = p_grant_type
       and (p_grant_type = 'site_admin' or g.guild_id = v_guild)
  ) then
    raise exception 'That Discord account already has % access', p_label;
  end if;

  v_person := person_for_discord_id(p_discord_id);

  insert into guild_grants (person_id, guild_id, grant_type)
  values (v_person, v_guild, p_grant_type)
  returning guild_grants.id into v_id;

  perform write_audit_log(null, p_grant_type || '_granted', p_grant_type, v_id,
    jsonb_build_object('discord_id', p_discord_id, 'guild_id', v_guild));

  return v_id;
end;
$$;

create function public.admin_revoke(p_grant_type text, p_discord_id text, p_label text, p_guild_id integer)
returns void
language plpgsql security definer set search_path to 'public'
as $$
declare
  v_guild integer;
  v_id integer;
begin
  if not public.is_site_admin() then
    raise exception 'Not authorized';
  end if;

  if p_grant_type = 'site_admin'
     and (select count(*) from guild_grants where grant_type = 'site_admin') <= 1 then
    raise exception 'Cannot revoke the last remaining site admin';
  end if;

  if p_grant_type <> 'site_admin' then
    v_guild := coalesce(p_guild_id, only_guild_id());
  end if;

  delete from guild_grants g
   using people p
   where p.id = g.person_id
     and p.discord_id = p_discord_id
     and g.grant_type = p_grant_type
     and (p_grant_type = 'site_admin' or g.guild_id = v_guild)
  returning g.id into v_id;

  if v_id is null then
    raise exception 'That Discord account does not have % access', p_label;
  end if;

  perform write_audit_log(null, p_grant_type || '_revoked', p_grant_type, v_id,
    jsonb_build_object('discord_id', p_discord_id, 'guild_id', v_guild));
end;
$$;

create function public.admin_list_grants(p_grant_type text)
returns table(id integer, discord_id text, auth_user_id uuid, display_name text, guild_id integer)
language plpgsql security definer set search_path to 'public'
as $$
begin
  if not public.is_site_admin() then
    raise exception 'Not authorized';
  end if;

  return query
    select g.id, p.discord_id, p.auth_user_id,
      coalesce(u.raw_user_meta_data ->> 'full_name', u.raw_user_meta_data ->> 'name'),
      g.guild_id
    from guild_grants g
    join people p on p.id = g.person_id
    left join auth.users u on u.id = p.auth_user_id
    where g.grant_type = p_grant_type
    order by g.id;
end;
$$;

