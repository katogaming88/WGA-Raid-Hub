create or replace function public.set_encounter_cap(p_encounter_id integer, p_cap integer default null)
returns void
language plpgsql security definer set search_path to 'public'
as $$
begin
  if auth.uid() is null then
    raise exception 'Not signed in';
  end if;

  -- The cap is Blizzard's, the same for every guild: a site admin keeps it
  -- right, and no guild role changes it (#1324).
  if not public.is_site_admin() then
    raise exception 'Not authorized';
  end if;

  if not exists (select 1 from raid_encounters where id = p_encounter_id) then
    raise exception 'That boss is not in the raid list yet.';
  end if;

  if p_cap is not null and (p_cap <= 0 or p_cap > 30) then
    raise exception 'A boss cap has to be between 1 and 30.';
  end if;

  update raid_encounters set cap = p_cap where id = p_encounter_id;

  insert into public.audit_log (team_id, actor_id, action, target_type, target_id, detail)
  values (null, auth.uid(), 'Set Boss Cap', 'raid_encounters', p_encounter_id, jsonb_build_object('cap', p_cap));
end;
$$;

create or replace function public.set_guild_officer_bios(p_bios jsonb)
returns jsonb
language plpgsql security definer set search_path to 'public'
as $$
declare
  v_bios jsonb;
begin
  -- Any guild: the bio cards are stored once for the whole site until #1647.
  if not (public.is_site_admin() or public.is_guild_officer()) then
    raise exception 'Not authorized';
  end if;

  update public.site_settings
  set guild_officer_bios = p_bios, updated_at = now()
  where id = 1
  returning guild_officer_bios into v_bios;

  insert into public.audit_log (team_id, actor_id, action, target_type, target_id, detail)
  values (null, auth.uid(), 'Guild Officer Bios Saved', 'site_settings', null,
          jsonb_build_object('count', jsonb_array_length(p_bios)));

  return v_bios;
end;
$$;

-- A guild officer sees a person's teams in their own guilds only

create or replace function public.resolve_person(p_discord_id text)
returns jsonb
language plpgsql stable security definer set search_path to 'public'
as $$
declare
  v_is_self boolean := p_discord_id is not distinct from public.current_discord_id();
  v_is_site_admin boolean := public.is_site_admin();
  v_guild_team_ids integer[] := public.my_guild_officer_team_ids();
  v_sees_all_teams boolean;
  v_person people%rowtype;
  v_grants text[];
  v_result jsonb;
begin
  v_sees_all_teams := v_is_self or v_is_site_admin;

  if not (v_sees_all_teams or public.is_any_team_officer() or cardinality(v_guild_team_ids) > 0) then
    raise exception 'Not authorized';
  end if;

  select * into v_person from people where discord_id = p_discord_id;

  select coalesce(array_agg(g.grant_type), '{}') into v_grants
    from guild_grants g
   where g.person_id = v_person.id;

  if p_discord_id is null
     or not (
       exists (select 1 from team_members where person_id = v_person.id)
       or cardinality(v_grants) > 0
     ) then
    return null;
  end if;

  select jsonb_build_object(
    'discord_id', p_discord_id,
    'auth_user_id', v_person.auth_user_id,
    'site_admin', case when v_is_self or v_is_site_admin
                       then 'site_admin' = any (v_grants) end,
    'guild_officer', case when v_is_self or v_is_site_admin
                          then 'guild_officer' = any (v_grants) end,
    'boe_manager', 'boe_manager' = any (v_grants),
    'teams', coalesce((
      select jsonb_agg(
               jsonb_build_object(
                 'team_id', tm.team_id,
                 'team_member_id', tm.id,
                 'role', tm.role,
                 'archived_at', tm.archived_at,
                 'characters', coalesce((
                   select jsonb_agg(
                            jsonb_build_object(
                              'player_id', p.id,
                              'name_realm', p.name_realm,
                              'url_code', p.url_code,
                              'archived_at', p.archived_at
                            )
                            order by p.archived_at desc nulls first, p.name_realm
                          )
                     from players p
                    where p.team_member_id = tm.id
                 ), '[]'::jsonb)
               )
               order by tm.team_id
             )
        from team_members tm
       where tm.person_id = v_person.id
         and (v_sees_all_teams
              or tm.team_id = any (v_guild_team_ids)
              or public.my_team_role(tm.team_id) = any (array['officer', 'team_leader']))
    ), '[]'::jsonb)
  )
  into v_result;

  return v_result;
end;
$$;

