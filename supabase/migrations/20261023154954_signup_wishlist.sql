-- #1609: someone signed up on a character that is not on the roster yet (a new
-- main, a swap, a first main) fills in next season's wishlist before signups
-- close, and it moves onto their roster character when the signup is added.
--
-- A wishlist row belongs to a roster character (item_preferences.player_id),
-- so such a signup had nothing to put one on until signups closed, which can
-- be as late as the season's start (#1608). The signup's rows live in a table
-- of their own rather than as item_preferences rows with no player: priority,
-- the RCLootCouncil export, BiS demand, setup status and the current site all
-- read item_preferences and expect a roster character on every row, and none
-- of them should see a signup's picks before the season starts.
--
-- No season column: a signup is for one season, and its rows take it from
-- there when they move. One row per item and slot, as item_preferences holds
-- per season. Removing the signup removes them (cascade).

create table public.signup_item_preferences (
  id integer generated by default as identity primary key,
  signup_id integer not null references public.season_signups(id) on delete cascade,
  item_id integer not null references public.items(id) on delete cascade,
  status text not null check (status = any (array['bis', 'good', 'ok', 'catalyst', 'pass'])),
  slot text,
  note text,
  synced_bis boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz
);

create unique index signup_item_preferences_no_dupe_item_key
  on public.signup_item_preferences (signup_id, item_id, coalesce(slot, ''));

alter table public.signup_item_preferences owner to postgres;
alter table public.signup_item_preferences enable row level security;

create trigger trg_signup_item_preferences_updated_at
  before update on public.signup_item_preferences
  for each row execute function public.set_updated_at();

-- The signups whose wishlist the caller fills in: their own, by person or, for
-- one the current site took, by account (as declare_season_signup() finds
-- it), still waiting to be added, on a character the team's roster does not
-- hold. A character already on the roster has its own wishlist. Security
-- definer because raiders cannot read season_signups.
create function public.my_wishlist_signup_ids() returns integer[]
language sql stable security definer set search_path = public
as $$
  select coalesce(array_agg(s.id), '{}')
    from season_signups s
   where (s.person_id = my_person_id() or (s.person_id is null and s.auth_user_id = auth.uid()))
     and s.status in ('pending', 'approved')
     and not exists (
           select 1 from players p
            where p.team_id = s.team_id
              and p.archived_at is null
              and p.name_realm_key = lower(replace(s.signup_name_realm, ' ', ''))
         );
$$;

revoke all on function public.my_wishlist_signup_ids() from public, anon;
grant execute on function public.my_wishlist_signup_ids() to authenticated;

-- Whether the team has opened the wishlist for the signup's season. Security
-- definer for the same reason; it says nothing team_seasons does not.
create function public.signup_wishlist_open(p_signup_id integer) returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from season_signups s
      join team_seasons ts on ts.team_id = s.team_id and ts.season_code = s.season
     where s.id = p_signup_id and ts.wishlist_open
  );
$$;

revoke all on function public.signup_wishlist_open(integer) from public, anon;
grant execute on function public.signup_wishlist_open(integer) to authenticated;

create policy "Claude readers read signup_item_preferences" on public.signup_item_preferences
  for select to claude_readers using (true);
create policy "Raiders manage own signup_item_preferences" on public.signup_item_preferences
  using (signup_id = any ((select my_wishlist_signup_ids())::integer[]))
  with check (signup_id = any ((select my_wishlist_signup_ids())::integer[]));

-- Writes only while the season's wishlist is open, refused out loud as
-- restrict_item_preferences_to_open_wishlist() does: a closed check in the
-- rule above would report an update or delete as done with nothing changed.
-- Only a raider's own write is checked; the move below runs as the owner.
create function public.restrict_signup_item_preferences_to_open_wishlist() returns trigger
language plpgsql set search_path = public
as $$
declare
  v_signup_id integer;
begin
  if current_user = 'authenticated' then
    foreach v_signup_id in array case
        when tg_op = 'INSERT' then array[new.signup_id]
        when tg_op = 'DELETE' then array[old.signup_id]
        else array[old.signup_id, new.signup_id]
      end
    loop
      if not public.signup_wishlist_open(v_signup_id) then
        raise exception 'wishlist editing is not open for that season on this team';
      end if;
    end loop;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end $$;

create trigger trg_signup_item_preferences_wishlist_open
  before insert or update or delete on public.signup_item_preferences
  for each row execute function public.restrict_signup_item_preferences_to_open_wishlist();

-- The signup's rows follow it. Added to the roster (add_signup_to_roster(),
-- whoever calls it: closing signups, an officer's single add, the automatic
-- close of #1608): they become the roster character's wishlist for the
-- season, in place of any it held there, which only a character brought back
-- from the archive can have. A swap's old character is a different row and
-- keeps its own. Turned down, or moved to another character: they go, since
-- they were picks for that character. Security definer because the add can be
-- an officer's, who may not write a raider's wishlist.
create function public.carry_signup_wishlist() returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if new.status = 'added' and new.approved_player_id is not null then
    if exists (select 1 from signup_item_preferences where signup_id = new.id) then
      delete from item_preferences
       where player_id = new.approved_player_id and season = new.season;
      insert into item_preferences (team_id, player_id, item_id, status, note, slot, season, synced_bis)
      select new.team_id, new.approved_player_id, item_id, status, note, slot, new.season, synced_bis
        from signup_item_preferences
       where signup_id = new.id;
    end if;
  elsif new.status <> 'rejected'
        and lower(replace(new.signup_name_realm, ' ', '')) = lower(replace(old.signup_name_realm, ' ', '')) then
    return new;
  end if;

  delete from signup_item_preferences where signup_id = new.id;
  return new;
end $$;

revoke all on function public.carry_signup_wishlist() from public, anon, authenticated;

create trigger season_signups_carry_wishlist
  after update of status, signup_name_realm on public.season_signups
  for each row
  when (new.status is distinct from old.status or new.signup_name_realm is distinct from old.signup_name_realm)
  execute function public.carry_signup_wishlist();

