-- #1717: a season can be on file before Blizzard dates it (the database half
-- of #1714).
--
-- Blizzard dates a season about two weeks ahead, so a season that had to be
-- on file with a start date left no window to collect signups early. Now:
--
-- * seasons.starts_at may be empty. An expansion's seasons go in together,
--   undated; each is dated later by one short migration that sets its start
--   and the previous season's end, the day before.
-- * An undated season has no end either, and the no-overlap and window
--   checks skip it, so it is never the current season and matches no raid
--   date.
-- * seasons.position orders them. Dated seasons go by date; undated ones come
--   after every dated one, by position, so "the next season" is the first
--   undated one. Existing rows are numbered by date; a new row takes the
--   next number unless its migration names one.
-- * No undated season is added here. Midnight Season 3 goes in with #1714,
--   whose pages learn to show an undated season: today's pages would sort it
--   first, since an empty date sorts first in a newest-first list.
--
-- The eight functions that read starts_at, with an undated season:
--
--   current_season, close_started_season_signups, fill_raid_night,
--   declare_season_signup, team_season_start   already right: never
--     current, never auto-closed or matched to a raid night, takes signups,
--     and has no start of its own (null)
--   close_season          refused: it slipped past "has not ended", since a
--     comparison with an empty date is neither true nor false
--   promote_season_signups  the 14-day rule goes: leaders close signups
--     whenever they choose (Kat, 2026-10-30)
--   wishlist_setup_status   an undated next season's open wishlist counts,
--     as a dated future one's does, and sorts last

alter table public.seasons alter column starts_at drop not null;

alter table public.seasons drop constraint seasons_no_overlap;
alter table public.seasons add constraint seasons_no_overlap
  exclude using gist (daterange(starts_at, ends_at, '[]') with &&) where (starts_at is not null);

alter table public.seasons drop constraint seasons_window_check;
alter table public.seasons add constraint seasons_window_check check (
  (starts_at is not null or ends_at is null) and (ends_at is null or ends_at >= starts_at)
);

alter table public.seasons add column position integer;
update public.seasons s
   set position = r.n
  from (select code, row_number() over (order by starts_at, code) as n from public.seasons) r
 where r.code = s.code;
alter table public.seasons alter column position set not null;
alter table public.seasons alter column position add generated by default as identity (start with 1000);
alter table public.seasons add constraint seasons_position_key unique (position);

comment on column public.seasons.starts_at is
  'The day the season launched. Empty until Blizzard dates it (#1717): an undated season is never current and matches no raid date.';
comment on column public.seasons.ends_at is
  'Null while the season is open-ended, and always for an undated one; the migration that dates the next season sets it. Dated seasons do not overlap (seasons_no_overlap).';
comment on column public.seasons.position is
  'The order of seasons (#1717). Dated seasons sort by starts_at; undated ones come after them by position, so the next season is the first undated one.';

CREATE OR REPLACE FUNCTION public.close_season(p_team_id integer, p_season text, p_roster_snapshot jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_config jsonb;
  v_tier public.seasons%rowtype;
  v_current_start date;
  v_raids jsonb;
  v_entry jsonb;
begin
  -- Locked through the same select the write rule filters, so a caller the
  -- rule refuses sees no row and gets one Not authorized.
  select config into v_config from public.team_settings where team_id = p_team_id for update;
  if v_config is null then
    raise exception 'Not authorized';
  end if;

  select * into v_tier from public.seasons where code = p_season;
  if not found then
    raise exception '% is not a season this site knows', p_season;
  end if;

  select s.starts_at into v_current_start
    from public.seasons s where s.code = public.current_season();
  -- An undated season has not started, let alone ended.
  if v_current_start is null or v_tier.starts_at is null or v_tier.starts_at >= v_current_start then
    raise exception '% has not ended', v_tier.display_name;
  end if;

  if coalesce(v_config -> 'seasonHistory', '[]'::jsonb) @> jsonb_build_array(jsonb_build_object('code', p_season)) then
    raise exception '% is already closed for this team', v_tier.display_name;
  end if;

  -- The tier's raids with the team's progress folded in: a zone appears when
  -- the team has a progress row on any of its bosses, in zone and boss order.
  select coalesce(jsonb_agg(
    jsonb_build_object(
      'name', rz.name,
      'wclZoneId', rz.wcl_zone_id,
      'isMiniRaid', rz.is_mini_raid,
      'bosses', (
        select coalesce(jsonb_agg(
          jsonb_build_object(
            'name', re.name,
            'wclEncounterId', re.wcl_encounter_id,
            'mythicDate', trp.mythic_date,
            'mythicPulls', trp.mythic_pulls,
            'mythicBestPct', trp.mythic_best_pct
          )
          order by re.sort_index, re.id
        ), '[]'::jsonb)
          from public.raid_encounters re
          left join public.team_raid_progress trp
            on trp.encounter_id = re.id and trp.team_id = p_team_id
         where re.zone_id = rz.id
      )
    )
    order by rz.sort_index, rz.id
  ), '[]'::jsonb)
    into v_raids
    from public.raid_zones rz
   where rz.season = p_season
     and exists (
       select 1 from public.raid_encounters re
         join public.team_raid_progress trp on trp.encounter_id = re.id
        where re.zone_id = rz.id and trp.team_id = p_team_id
     );

  v_entry := jsonb_build_object(
    'code', v_tier.code,
    'name', v_tier.display_name,
    'start', public.team_season_start(p_team_id, p_season),
    'end', v_tier.ends_at,
    'raids', v_raids,
    'roster', coalesce(p_roster_snapshot, '[]'::jsonb)
  );

  update public.team_settings
     set config = config || jsonb_build_object(
       'seasonHistory', coalesce(v_config -> 'seasonHistory', '[]'::jsonb) || jsonb_build_array(v_entry)
     )
   where team_id = p_team_id
   returning config into v_config;
  if not found then
    raise exception 'Not authorized';
  end if;

  -- A new tier resets what the roster carries forward (#498): M+ exclusion,
  -- Bench, and the submitted BiS link. Trial status is left alone.
  update public.players
     set m_plus_excluded = false, m_plus_note = null
   where team_id = p_team_id and archived_at is null and m_plus_excluded = true;

  update public.players
     set is_bench = false
   where team_id = p_team_id and archived_at is null and is_bench = true;

  update public.players
     set bis_link = null
   where team_id = p_team_id and archived_at is null and bis_link is not null;

  -- Skipped only when nobody is signed in (a service-role call), because
  -- write_audit_log() needs an actor and would otherwise abort the close.
  if auth.uid() is not null then
    perform public.write_audit_log(
      p_team_id, 'Season Closed', 'team_settings', p_team_id, jsonb_build_object('season', p_season)
    );
  end if;

  return v_config;
end;
$function$;

CREATE OR REPLACE FUNCTION public.promote_season_signups(p_team_id integer, p_season text, p_expected text, p_archive_player_ids integer[] DEFAULT '{}'::integer[])
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_plan jsonb;
  v_step record;
  v_season_name text;
  v_reviewer integer;
  v_player_id integer;
begin
  if auth.uid() is null then
    raise exception 'Not signed in';
  end if;
  if not (p_team_id = any (public.my_leader_team_ids()) or public.is_site_admin()) then
    raise exception 'Not authorized';
  end if;

  select display_name into v_season_name from public.seasons where code = p_season;
  if v_season_name is null then
    raise exception '% is not a season this site knows', p_season;
  end if;

  -- 1.
  perform 1 from public.season_signups
   where team_id = p_team_id and season = p_season
   order by id
     for update;

  -- 2.
  perform 1 from public.team_members tm
   where tm.team_id = p_team_id
     and (exists (select 1 from public.players p
                   where p.team_member_id = tm.id and p.archived_at is null)
          or exists (select 1 from public.season_signups s
                       join public.people pe on pe.id = tm.person_id
                      where s.team_id = p_team_id and s.season = p_season
                        and (s.person_id = pe.id or (s.person_id is null and s.auth_user_id = pe.auth_user_id))))
   order by tm.id
     for share;

  -- 3.
  v_plan := public.signup_promotion_plan(p_team_id, p_season);
  if md5(v_plan::text) is distinct from p_expected then
    raise exception 'The signups or the roster changed since the preview was read. Read it again.';
  end if;
  if exists (
    select unnest(coalesce(p_archive_player_ids, '{}'))
    except
    select (e ->> 'player_id')::integer from jsonb_array_elements(v_plan) e where e ->> 'kind' = 'archives'
  ) then
    raise exception 'A character to archive is not one the preview lists. Read it again.';
  end if;

  select id into v_reviewer from public.team_members
   where team_id = p_team_id and person_id = public.my_person_id();

  -- 4.
  for v_step in
    select x.signup_id, x.from_player_id, s.is_trial, s.is_backup_tank, s.is_backup_healer
      from jsonb_to_recordset(v_plan) as x(kind text, signup_id integer, from_player_id integer)
      join public.season_signups s on s.id = x.signup_id
     where x.kind in ('stays', 'swaps', 'first_mains', 'joins')
     order by x.signup_id
  loop
    update public.season_signups
       set status = 'approved', reviewed_at = now(), reviewed_by = v_reviewer
     where id = v_step.signup_id and status = 'pending';
    perform public.add_signup_to_roster(
      v_step.signup_id, coalesce(v_step.is_trial, true), v_step.from_player_id,
      v_step.is_backup_tank, v_step.is_backup_healer
    );
  end loop;

  -- 5.
  for v_player_id in
    select distinct unnest(coalesce(p_archive_player_ids, '{}')) order by 1
  loop
    perform public.archive_player(v_player_id, 'no_signup', v_season_name);
    perform public.write_audit_log(
      p_team_id, 'Player Removed', 'players', v_player_id, to_jsonb('no_signup: ' || v_season_name)
    );
  end loop;

  -- 6.
  perform public.set_team_season(p_team_id, p_season, false, null);
end;
$function$;

CREATE OR REPLACE FUNCTION public.wishlist_setup_status(p_team_id integer)
 RETURNS TABLE(player_id integer, name_realm text, discord_id text, wishlist_count integer, bis_link text, missing_bis_rows text[], season text, season_name text)
 LANGUAGE plpgsql
 STABLE
 SET search_path TO 'public'
AS $function$
declare
  wishlist_slots text[] := array[
    'Head','Neck','Shoulder','Back','Chest','Wrist','Hands','Waist','Legs','Feet',
    'Finger 1','Finger 2','Trinket 1','Trinket 2','Weapon','Off Hand'
  ];
  live_code text := current_season();
  prec record;
  bi record;
  candidates text[];
  bis_rows text[];
  off_hand_required boolean;
  required_rows text[];
  missing text[];
begin
  for prec in
    with live as (
      select s.code, s.display_name, s.starts_at from seasons s where s.code = live_code
    ),
    opened as (
      select s.code, s.display_name, s.starts_at
      from team_seasons ts
      join seasons s on s.code = ts.season_code
      join live l on s.starts_at is null or s.starts_at >= l.starts_at
      where ts.team_id = p_team_id
        and ts.wishlist_open
    )
    select p.id, p.name_realm, p.bis_link, pe.discord_id,
      t.code as tier_code, t.display_name as tier_name,
      (select count(*) from item_preferences ip
        where ip.player_id = p.id and ip.season = t.code) as wishlist_count
    from players p
    join team_members tm on tm.id = p.team_member_id
    join people pe on pe.id = tm.person_id
    -- The tiers a raider's own page lets them edit (#936): the team's open
    -- tiers from the live one on, and the live tier for a raider with the
    -- per-raider override. A union, so the two meet as one row.
    cross join lateral (
      select o.code, o.display_name, o.starts_at from opened o
      union
      select l.code, l.display_name, l.starts_at from live l where p.wishlist_allowed
    ) t
    where p.team_id = p_team_id
      and p.archived_at is null
    order by p.id, t.starts_at nulls last
  loop
    -- Raider's tags: wishlistCompleteness()'s bisRows/offHandRequired pass.
    -- item_preferences.slot is present for Finger/Trinket/Weapon/Off Hand
    -- disambiguation and every placeholder row, null (falls back to catalog
    -- slot) everywhere else.
    bis_rows := array[]::text[];
    off_hand_required := false;

    for bi in
      select ip.status, ip.slot as explicit_slot, i.slot as catalog_slot
      from item_preferences ip
      join items i on i.id = ip.item_id
      where ip.player_id = prec.id
        and ip.season = prec.tier_code
    loop
      if bi.explicit_slot is not null then
        candidates := array[bi.explicit_slot];
      else
        candidates := case bi.catalog_slot
          when 'Finger' then array['Finger 1', 'Finger 2']
          when 'Trinket' then array['Trinket 1', 'Trinket 2']
          when 'One-Hand' then array['Weapon']
          when 'Two-Hand' then array['Weapon']
          when 'Ranged' then array['Weapon']
          when 'Off Hand' then array['Off Hand']
          when 'Held In Off-hand' then array['Off Hand']
          when 'Head' then array['Head']
          when 'Neck' then array['Neck']
          when 'Shoulder' then array['Shoulder']
          when 'Back' then array['Back']
          when 'Chest' then array['Chest']
          when 'Wrist' then array['Wrist']
          when 'Hands' then array['Hands']
          when 'Waist' then array['Waist']
          when 'Legs' then array['Legs']
          when 'Feet' then array['Feet']
          else array[]::text[]
        end;
      end if;

      if bi.status = 'bis' then
        bis_rows := bis_rows || candidates;
        if (bi.explicit_slot = 'Weapon' or bi.explicit_slot is null) and bi.catalog_slot = 'One-Hand' then
          off_hand_required := true;
        end if;
      end if;
    end loop;

    required_rows := array(
      select s from unnest(wishlist_slots) s where s <> 'Off Hand' or off_hand_required
    );
    missing := array(
      select r from unnest(required_rows) r
      where not (bis_rows @> array[r])
    );

    player_id := prec.id;
    name_realm := prec.name_realm;
    discord_id := prec.discord_id;
    wishlist_count := prec.wishlist_count;
    bis_link := prec.bis_link;
    missing_bis_rows := missing;
    season := prec.tier_code;
    season_name := prec.tier_name;
    return next;
  end loop;
end;
$function$;
